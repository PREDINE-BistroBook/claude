/**
 * Writes src/server/db/migrations/bundle.ts: every migration's SQL inlined, in
 * the { journal, migrations: { m0000, … } } shape drizzle's durable-sqlite
 * migrator reads. Both runtimes apply migrations from it (db/migrate.ts) — the
 * Cloudflare Durable Object has no file system to read the .sql files from.
 *
 *   npm run db:bundle      (npm run db:generate runs it after drizzle-kit)
 *
 * drizzle-kit only writes its own bundle (migrations.js, .sql imports) when it
 * generates a migration for driver 'durable-sqlite'; inlining the SQL here
 * instead keeps the bundle importable by Vitest, tsc and wrangler alike, with
 * no .sql module rules. tests/unit/migrationsBundle.test.ts fails when the
 * committed bundle is out of step with the journal and the .sql files.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const MIGRATIONS_DIR = fileURLToPath(new URL('../src/server/db/migrations/', import.meta.url));
export const BUNDLE_FILE = path.join(MIGRATIONS_DIR, 'bundle.ts');

interface JournalEntry {
  idx: number;
  version: string;
  when: number;
  tag: string;
  breakpoints: boolean;
}

/** The bundle module's source for the migrations in `dir` (meta/_journal.json + <tag>.sql). */
export function renderMigrationsBundle(dir: string = MIGRATIONS_DIR): string {
  const journal = JSON.parse(fs.readFileSync(path.join(dir, 'meta/_journal.json'), 'utf8')) as {
    version: string;
    dialect: string;
    entries: JournalEntry[];
  };
  const lines: string[] = [
    '// Generated by scripts/bundle-migrations.ts from meta/_journal.json and the .sql files. Do not edit:',
    '// change db/schema.ts, then `npm run db:generate` (it rewrites this file too).',
    '',
    'export interface MigrationsBundle {',
    '  journal: { version: string; dialect: string; entries: { idx: number; version: string; when: number; tag: string; breakpoints: boolean }[] };',
    '  /** m0000, m0001, …: the SQL of each journal entry, statements split by "--> statement-breakpoint". */',
    '  migrations: Record<string, string>;',
    '}',
    '',
    'const bundle: MigrationsBundle = {',
    `  journal: ${JSON.stringify(journal)},`,
    '  migrations: {',
  ];
  for (const entry of journal.entries) {
    const file = path.join(dir, `${entry.tag}.sql`);
    if (!fs.existsSync(file)) throw new Error(`Missing migration file for journal entry ${entry.tag}`);
    const key = `m${String(entry.idx).padStart(4, '0')}`;
    lines.push(`    ${key}: ${JSON.stringify(fs.readFileSync(file, 'utf8'))},`);
  }
  lines.push('  },', '};', '', 'export default bundle;', '');
  return lines.join('\n');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const source = renderMigrationsBundle();
  const before = fs.existsSync(BUNDLE_FILE) ? fs.readFileSync(BUNDLE_FILE, 'utf8') : null;
  if (before === source) {
    console.log(`Migrations bundle is up to date (${path.relative(process.cwd(), BUNDLE_FILE)}).`);
  } else {
    fs.writeFileSync(BUNDLE_FILE, source);
    console.log(`Wrote ${path.relative(process.cwd(), BUNDLE_FILE)}.`);
  }
}
